-- Pick3 migration 003: medical expense records (병원·약국 결제 내역) per user.
-- Run once in Supabase SQL Editor AFTER SUPABASE_MIGRATION_002_users.sql. Safe to re-run.

create table if not exists public.pick3_medical_records (
  id bigint generated by default as identity primary key,
  user_id bigint references public.pick3_users(id) on delete cascade,
  patient text not null default '',
  provider text not null,
  kind text not null default '기타',        -- 병원 / 약국 / 안경 / 기타
  amount integer not null check (amount > 0),
  visit_date date not null,
  source text not null default '',          -- image / pdf
  created_at timestamptz not null default now()
);

-- Re-capturing the same screen (or overlapping scroll captures) must not double count.
create unique index if not exists pick3_medical_records_dedupe_uq
  on public.pick3_medical_records (user_id, patient, provider, visit_date, amount);
create index if not exists pick3_medical_records_user_date_idx
  on public.pick3_medical_records (user_id, visit_date desc);

-- Health data: RLS on, no policies. Only the server's secret key can read/write.
alter table public.pick3_medical_records enable row level security;
