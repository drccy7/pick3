-- Pick3 migration 004: prescription / dispensing records (처방조제정보) per user and customer.
-- Run once in Supabase SQL Editor AFTER SUPABASE_MIGRATION_002_users.sql. Safe to re-run.

create table if not exists public.pick3_prescriptions (
  id bigint generated by default as identity primary key,
  user_id bigint references public.pick3_users(id) on delete cascade,
  patient text not null default '',
  visit_date date not null,
  provider text not null,
  kind text not null default '처방',        -- 처방 (병·의원) / 조제 (약국)
  drug_name text not null,
  ingredient text not null default '',
  dose text not null default '',            -- 1회 투약량
  times_per_day text not null default '',   -- 1일 투여횟수
  days text not null default '',            -- 총 투약일수
  source text not null default '',          -- pdf / image
  created_at timestamptz not null default now()
);

-- Re-sending the same PDF must not duplicate rows.
create unique index if not exists pick3_prescriptions_dedupe_uq
  on public.pick3_prescriptions (user_id, patient, visit_date, provider, drug_name);
create index if not exists pick3_prescriptions_user_date_idx
  on public.pick3_prescriptions (user_id, visit_date desc);

-- Health data: RLS on, no policies. Only the server's secret key can read/write.
alter table public.pick3_prescriptions enable row level security;
