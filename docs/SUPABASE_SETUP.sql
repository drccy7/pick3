-- Run this once in Supabase SQL Editor if using Supabase for persistent storage
create table if not exists public.pick3_saved_places (
  id bigint generated by default as identity primary key,
  name text not null,
  area text not null default '',
  address text not null default '',
  category text not null default '',
  signature_menu text not null default '',
  memo text not null default '',
  lat double precision,
  lng double precision,
  phone text not null default '',
  kakao_url text not null default '',
  naver_url text not null default '',
  created_at timestamptz not null default now()
);
