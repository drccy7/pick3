-- Pick3 migration 002: per-user tokens, per-user saved lists, daily usage limits.
-- Run once in Supabase SQL Editor AFTER docs/SUPABASE_SETUP.sql. Safe to re-run.
-- Then register users with: python scripts/pick3_users.py add <이름>

-- 1) Users. Only a SHA-256 hash of each token is stored; the token itself is shown once.
create table if not exists public.pick3_users (
  id bigint generated by default as identity primary key,
  name text not null,
  token_hash text not null unique,
  daily_limit int,                         -- null = server default (PICK3_DAILY_LIMIT_PER_USER)
  disabled boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.pick3_users enable row level security;

-- 2) Saved places belong to a user; duplicates are per user.
alter table public.pick3_saved_places
  add column if not exists user_id bigint references public.pick3_users(id) on delete cascade;
drop index if exists public.pick3_saved_places_name_addr_uq;
create unique index if not exists pick3_saved_places_user_name_addr_uq
  on public.pick3_saved_places (user_id, name, address);
create index if not exists pick3_saved_places_user_created_idx
  on public.pick3_saved_places (user_id, created_at desc);

-- 3) Daily ingest counter (KST day) used to cap Gemini cost per user and overall.
create table if not exists public.pick3_usage (
  user_id bigint not null references public.pick3_users(id) on delete cascade,
  day date not null,
  count int not null default 0,
  primary key (user_id, day)
);
alter table public.pick3_usage enable row level security;

create or replace function public.pick3_bump_usage(p_user bigint)
returns json
language plpgsql
security invoker
set search_path = public
as $$
declare
  d date := (now() at time zone 'Asia/Seoul')::date;
  u int;
  t int;
begin
  insert into pick3_usage (user_id, day, count) values (p_user, d, 1)
  on conflict (user_id, day) do update set count = pick3_usage.count + 1
  returning count into u;
  select coalesce(sum(count), 0) into t from pick3_usage where day = d;
  return json_build_object('user_count', u, 'total_count', t);
end
$$;

-- Only the server's secret key (service_role) may call it.
revoke execute on function public.pick3_bump_usage(bigint) from public, anon, authenticated;
grant execute on function public.pick3_bump_usage(bigint) to service_role;
